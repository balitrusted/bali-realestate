export function getSeedQuestions(): QaQuestion[] {
  return QA_SEED_QUESTIONS.map((q) => ({ ...q }));
}

export function getSeedAnswers(): QaAnswer[] {
  return QA_SEED_ANSWERS.map((a) => ({ ...a }));
}

export function getSeedQuestionBySlug(slug: string): QaQuestion | undefined {
  return getSeedQuestions().find((q) => q.slug === slug);
}

export function getSeedAnswersForQuestion(questionId: string): QaAnswer[] {
  return getSeedAnswers().filter((a) => a.questionId === questionId && a.status === "approved");
}
