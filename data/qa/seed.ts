function daysAgo(n: number, hour = 14, minute = 0): string {
  const d = new Date();
  d.setUTCDate(d.getUTCDate() - n);
  d.setUTCHours(hour, minute, 0, 0);
  return d.toISOString();
}

function hoursAgo(n: number): string {
  const d = new Date();
  d.setTime(d.getTime() - n * 60 * 60 * 1000);
  return d.toISOString();
}

